-- =====================================================================
--  Миграция 0001: координаты свидетельства на связи note_to_point
--
--  Назначение: исправить отображение мест без фиксированной координаты
--  (кладбище, улица/площадь и т.п.). Раньше координаты таких свидетельств
--  складывались в point_coordinates (на уровне места) и на карте
--  усреднялись в один маркер. Теперь каждая связь «свидетельство ↔ место»
--  может нести собственную координату.
--
--  Для мест с фиксированной координатой эти поля остаются NULL —
--  координата по-прежнему берётся из point_coordinates.
--
--  Применение (на существующей базе):
--    psql -U root -d db -f ./migrations/0001_note_to_point_coordinates.sql
--  На чистой базе таблицы создаются из моделей (create_all) уже с этими
--  колонками — миграция не нужна.
-- =====================================================================

ALTER TABLE note_to_point
    ADD COLUMN IF NOT EXISTS latitude  double precision,
    ADD COLUMN IF NOT EXISTS longitude double precision;
