-- --- Починка счётчиков id ---------------------------------------------
-- Данные выше вставлены с явными id, из-за чего счётчики (sequences) после
-- RESTART IDENTITY остаются на 1. Выставляем каждый на MAX(id)+1, иначе
-- новые записи через API конфликтуют по первичному ключу.
DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN
        SELECT s.relname AS seq_name, t.relname AS tbl_name, a.attname AS col_name
        FROM pg_class s
        JOIN pg_depend d  ON d.objid = s.oid AND d.deptype = 'a'
        JOIN pg_class t   ON t.oid = d.refobjid
        JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = d.refobjsubid
        WHERE s.relkind = 'S'
    LOOP
        EXECUTE format(
            'SELECT setval(%L, COALESCE((SELECT MAX(%I) FROM %I), 0) + 1, false)',
            r.seq_name, r.col_name, r.tbl_name
        );
    END LOOP;
END $$;

COMMIT;

